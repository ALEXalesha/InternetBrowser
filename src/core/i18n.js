  function lang(l) {
    return l === 'en' ? 'en' : 'ru';
  }

  /** Строка по ключу с подстановкой {имя}; неизвестный ключ возвращается как есть. */
  function t(l, key, vars) {
    const s = STRINGS[lang(l)][key];
    if (s === undefined) return key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k]))) : s;
  }

  function table(l) {
    return Object.assign({}, STRINGS[lang(l)]);
  }

  return { STRINGS, t, table, lang };
